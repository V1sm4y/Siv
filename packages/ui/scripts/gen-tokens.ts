import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { games } from '@arena/game-registry';
import { brandTheme, dark, light, duration, easing, elevation, radius, spacing, typeScale, type Palette } from '../src/tokens';

// surface0 -> surface-0, lineStrong -> line-strong (must match the var names used in styles/index.css)
const kebab = (s: string) => s.replace(/[A-Z]/g, (c) => `-${c.toLowerCase()}`).replace(/([a-z])(\d)/g, '$1-$2');
const vars = (p: Palette) =>
  Object.entries(p).map(([k, v]) => `  --${kebab(k)}: ${v};`).join('\n');

const gameBlocks = games
  .map(
    (g) => `[data-game='${g.id}'] {
  --accent: ${g.theme.accent};
  --accent-fg: ${g.theme.accentFg};
  --accent-text: ${g.theme.accentText};
  --grad-1: ${g.theme.gradient[0]};
  --grad-2: ${g.theme.gradient[1]};
  --grad-3: ${g.theme.gradient[2]};
}
[data-theme='light'] [data-game='${g.id}'] { --accent-text: ${g.theme.accentTextLight}; }`,
  )
  .join('\n');

const first = { theme: brandTheme };
const css = `/* GENERATED by scripts/gen-tokens.ts from src/tokens.ts and the Game Modules. Do not edit. */

/* Registered so the accent can interpolate smoothly when switching game containers. */
@property --accent { syntax: '<color>'; inherits: true; initial-value: ${first.theme.accent}; }
@property --accent-fg { syntax: '<color>'; inherits: true; initial-value: ${first.theme.accentFg}; }
@property --accent-text { syntax: '<color>'; inherits: true; initial-value: ${first.theme.accentText}; }

:root {
${vars(dark)}
  --accent: ${first.theme.accent};
  --accent-fg: ${first.theme.accentFg};
  --accent-text: ${first.theme.accentText};
  --grad-1: ${first.theme.gradient[0]};
  --grad-2: ${first.theme.gradient[1]};
  --grad-3: ${first.theme.gradient[2]};
${Object.entries(duration).map(([k, v]) => `  --dur-${k}: ${v}ms;`).join('\n')}
${Object.entries(spacing).map(([k, v]) => `  --space-${k}: ${v};`).join('\n')}
  --elev-1: ${elevation.dark[1]};
  --elev-2: ${elevation.dark[2]};
  --elev-3: ${elevation.dark[3]};
  --focus-ring: var(--accent-text);
  color-scheme: dark;
}

:root[data-theme='light'] {
${vars(light)}
  --elev-1: ${elevation.light[1]};
  --elev-2: ${elevation.light[2]};
  --elev-3: ${elevation.light[3]};
  --accent-text: ${brandTheme.accentTextLight};
  color-scheme: light;
}

${gameBlocks}

/* Accent morph on container switch (background-color et al. follow these registered properties). */
:root, [data-game] {
  transition: --accent var(--dur-route) ${easing.out}, --accent-fg var(--dur-route) ${easing.out}, --accent-text var(--dur-route) ${easing.out};
}

@theme {
${Object.entries(radius).map(([k, v]) => `  --radius-${k}: ${v};`).join('\n')}
  --ease-out: ${easing.out};
  --ease-in-out: ${easing.inOut};
  --ease-spring: ${easing.spring};
${Object.entries(typeScale).map(([k, [size, lh]]) => `  --text-${k}: ${size};\n  --text-${k}--line-height: ${lh};`).join('\n')}
}
`;

const out = join(dirname(fileURLToPath(import.meta.url)), '../src/styles/tokens.generated.css');
mkdirSync(dirname(out), { recursive: true });
writeFileSync(out, css);
console.log(`gen-tokens: wrote ${out} (${games.length} game themes)`);
