// Discovers packages/games/*/src/module.ts and emits the registry. Adding a game = adding a folder.
import { readdirSync, existsSync, writeFileSync, mkdirSync } from 'node:fs';
import { join, dirname, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');

export function discover(gamesDir) {
  return readdirSync(gamesDir, { withFileTypes: true })
    .filter((d) => d.isDirectory() && existsSync(join(gamesDir, d.name, 'src/module.ts')))
    .map((d) => d.name)
    .sort();
}

export function generate({ gamesDir = join(root, 'packages/games'), out = join(root, 'packages/game-registry/src/generated.ts') } = {}) {
  const ids = discover(gamesDir);
  const rel = (id) => relative(dirname(out), join(gamesDir, id, 'src/module')).split('\\').join('/');
  const lines = [
    '// GENERATED by tooling/gen-modules.mjs. Do not edit; do not commit.',
    "import type { GameModule } from '@arena/game-sdk';",
    ...ids.map((id, i) => `import m${i} from '${rel(id)}';`),
    '',
    `export const GAME_MODULES: readonly GameModule[] = [${ids.map((_, i) => `m${i}`).join(', ')}];`,
    '',
  ];
  mkdirSync(dirname(out), { recursive: true });
  writeFileSync(out, lines.join('\n'));
  return ids;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const ids = generate();
  console.log(`gen-modules: ${ids.length} module(s): ${ids.join(', ')}`);
}
